import { test, expect } from "@playwright/test";
import { readFile, mkdir } from "node:fs/promises";
import { createHmac } from "node:crypto";

test("inbound bindings remain opt-in, signed receipts deduplicate and disabled bindings reject dispatch", async ({ page }) => {
  test.setTimeout(60_000);
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" && !m.text().includes("Failed to load resource")) errors.push(m.text()); });
  page.on("response", r => { if (r.status() >= 500) errors.push(`${r.status()} ${r.url()}`); });
  page.on("dialog", d => d.accept());
  const session = JSON.parse(await readFile("/tmp/sherlock-foundation-qa/ai-session.json", "utf8"));
  await page.context().addCookies(session.cookies);
  await page.goto("/settings#inbound");
  await expect(page).toHaveTitle(/Sherlock/);
  await expect(page.getByRole("heading", { name: "Inbound alerts", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "No inbound bindings" })).toBeVisible();
  const policyBefore = await (await page.request.get("/api/v1/automation/policy")).json();
  expect(policyBefore.mode).toBe("off");
  expect(policyBefore.tools_enabled).toBe(false);
  await page.getByRole("button", { name: "Add inbound binding" }).click();
  const drawer = page.getByRole("dialog");
  await expect(drawer.getByLabel("Enable this inbound binding")).not.toBeChecked();
  await drawer.getByLabel("Binding name").fill("Checkout monitoring");
  const services = await (await page.request.get("/api/v1/services")).json();
  await drawer.getByLabel("Service and origin").selectOption(services.items[0].id);
  const secret = "inbound-browser-fixture-secret-32-bytes";
  await drawer.getByLabel("Signing secret", { exact: true }).fill(secret);
  await drawer.getByRole("button", { name: "Save inbound binding" }).click();
  await expect(drawer).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Enable binding", exact: true })).toBeVisible();
  const bindings = await (await page.request.get("/api/v1/inbound/bindings")).json();
  expect(JSON.stringify(bindings)).not.toContain(secret);
  expect(bindings.items[0].enabled).toBe(false);
  const path = `/api/v1/inbound/alerts/${bindings.items[0].id}`;
  const end = new Date(Math.floor(Date.now() / 300_000) * 300_000);
  const body = JSON.stringify({ version: "inbound-v1", event_id: "browser-event-1", title: "Connection acquisition timeouts reported by monitoring", start: new Date(end.getTime() - 900_000).toISOString(), end: end.toISOString() });
  const send = (raw = body) => {
    const timestamp = String(Math.floor(Date.now() / 1000));
    const signature = createHmac("sha256", secret).update(`${timestamp}.${raw}`).digest("hex");
    return page.request.post(path, { data: raw, headers: { "Content-Type": "application/json", "X-Sherlock-Timestamp": timestamp, "X-Sherlock-Signature": `v1=${signature}` } });
  };
  expect((await send()).status()).toBe(401);
  await page.getByRole("button", { name: "Enable binding", exact: true }).click();
  await expect(page.getByRole("button", { name: "Disable binding", exact: true })).toBeVisible();
  const accepted = await send(); expect(accepted.status()).toBe(202);
  const receipt = await accepted.json();
  const duplicate = await send(); expect(duplicate.status()).toBe(202);
  expect((await duplicate.json()).id).toBe(receipt.id);
  expect((await send(`${body} `)).status()).toBe(409);
  await expect(page.locator(".automation-entry")).toHaveCount(1, { timeout: 10_000 });
  await page.locator(".automation-entry summary").click();
  await expect(page.locator(".automation-entry")).toContainText("Automatic investigations are Off");
  await expect(page.locator(".automation-entry")).toContainText("External title:");
  const policyAfter = await (await page.request.get("/api/v1/automation/policy")).json();
  expect(policyAfter).toEqual(policyBefore);
  await mkdir("/tmp/sherlock-inbound-qa", { recursive: true });
  await page.screenshot({ path: "/tmp/sherlock-inbound-qa/desktop.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: "/tmp/sherlock-inbound-qa/mobile.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Edit binding", exact: true }).click();
  await expect(drawer.getByLabel("Replace signing secret")).toHaveValue("");
  await drawer.getByLabel("Investigations per UTC day").fill("3");
  await drawer.getByRole("button", { name: "Save inbound binding" }).click();
  await expect(drawer).toHaveCount(0);
  await page.reload();
  await expect(page.getByText("3 investigations/UTC day", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Disable binding", exact: true }).click();
  await expect(page.getByRole("button", { name: "Enable binding", exact: true })).toBeVisible();
  expect((await send()).status()).toBe(401);
  await page.getByRole("button", { name: "Delete binding", exact: true }).click();
  await expect(page.getByRole("heading", { name: "No inbound bindings" })).toBeVisible();
  expect(await page.locator("vite-error-overlay").count()).toBe(0);
  expect(errors).toEqual([]);
});
